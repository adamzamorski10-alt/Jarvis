"""
AI Manager — Domain Contracts.

Defines the strict, provider-neutral contracts for the AI Manager layer.

Trust boundary:
  - Fields marked "application-controlled" are generated by the application.
  - Fields marked "model-controlled" originate from the model and are UNTRUSTED.
  - All model-controlled data is validated before entering trusted application state.
"""
from __future__ import annotations

import re
from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from app.ai_manager.errors import AIManagerError as _AIManagerError


# ── Bounded constants ──────────────────────────────────────────────────────────

_MAX_USER_REQUEST_LENGTH = 65_536
_MAX_GOAL_LENGTH = 4_096
_MAX_CONTEXT_ENTRIES = 50
_MAX_CONTEXT_KEY_LENGTH = 128
_MAX_CONTEXT_VALUE_LENGTH = 4_096
_MAX_CONSTRAINTS_ENTRIES = 50
_MAX_CONSTRAINTS_KEY_LENGTH = 128
_MAX_CONSTRAINTS_VALUE_LENGTH = 2_048
_MAX_RATIONALE_LENGTH = 4_096
_MAX_WARNINGS = 20
_MAX_WARNING_LENGTH = 2_048
_MAX_ACTIONS = 20
_MAX_ACTION_ARGUMENTS = 50
_MAX_ARGUMENT_KEY_LENGTH = 128
_MAX_ARGUMENT_VALUE_LENGTH = 4_096
_MAX_CAPABILITIES = 20
_MAX_SUMMARY_LENGTH = 2_048
_MAX_METADATA_ENTRIES = 50
_MAX_METADATA_KEY_LENGTH = 128
_MAX_METADATA_VALUE_LENGTH = 4_096
_MAX_DEPENDENCIES = 20

_CAPABILITY_ID_PATTERN = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)*$")
_ACTION_ID_PATTERN = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
_ACTION_TYPE_PATTERN = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


# ── Decision outcome model ─────────────────────────────────────────────────────


class DecisionOutcome(str, Enum):
    """
    Minimal finite decision model.

    The model cannot directly transition application execution state.
    These outcomes represent what the AI Manager proposes; the application
    validates and decides what to do next.
    """
    REJECTED = "REJECTED"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"
    NEEDS_APPROVAL = "NEEDS_APPROVAL"
    PROPOSED = "PROPOSED"
    READY_FOR_PLANNING = "READY_FOR_PLANNING"


# ── Risk / approval model ──────────────────────────────────────────────────────


class RiskLevel(str, Enum):
    """Provider-neutral risk classification.  Application policy is authoritative."""
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class ApprovalRequirement(BaseModel):
    """
    Application-controlled approval requirement.

    The model may propose that approval is needed, but the application
    makes the final decision based on policy.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    required: bool = False
    reason: str | None = Field(default=None, max_length=2_048)
    approvers: list[str] = Field(default_factory=list, max_length=20)

    @field_validator("reason")
    @classmethod
    def _validate_reason(cls, v: str | None) -> str | None:
        if v is not None and not v.strip():
            return None
        return v.strip() if v else None


# ── Capability identifier ──────────────────────────────────────────────────────


class CapabilityIdentifier(BaseModel):
    """
    Namespaced capability identifier.

    These are identifiers only — they do NOT grant execution authority.
    The AI Manager may propose that a capability is required, but the
    application decides whether to authorize it.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    namespace: str = Field(min_length=1, max_length=64)
    name: str = Field(min_length=1, max_length=64)
    version: str | None = Field(default=None, max_length=32)

    @field_validator("namespace", "name")
    @classmethod
    def _validate_identifier_format(cls, v: str) -> str:
        if not _CAPABILITY_ID_PATTERN.match(v):
            raise ValueError(
                f"Identifier '{v}' must match ^[a-z][a-z0-9_]*(\\.[a-z][a-z0-9_]*)*$"
            )
        return v

    @field_validator("version")
    @classmethod
    def _validate_version(cls, v: str | None) -> str | None:
        if v is not None and not re.match(r"^[A-Za-z0-9_.-]{1,32}$", v):
            raise ValueError("version must match ^[A-Za-z0-9_.-]{1,32}$")
        return v

    def __str__(self) -> str:
        if self.version:
            return f"{self.namespace}.{self.name}:{self.version}"
        return f"{self.namespace}.{self.name}"


# ── Untrusted model output ─────────────────────────────────────────────────────


class RawActionProposal(BaseModel):
    """
    Untrusted action proposal from the model.

    ONLY these fields may be populated by the model.  Additional fields
    are rejected by ConfigDict(extra="forbid").
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    action_id: str = Field(min_length=1, max_length=64)
    capability_id: str = Field(min_length=1, max_length=128)
    action_type: str = Field(min_length=1, max_length=64)
    arguments: dict[str, Any] = Field(default_factory=dict, max_length=_MAX_ACTION_ARGUMENTS)
    dependencies: list[str] = Field(default_factory=list, max_length=_MAX_DEPENDENCIES)
    risk: RiskLevel = RiskLevel.LOW
    approval_required: bool = False
    summary: str = Field(min_length=1, max_length=_MAX_SUMMARY_LENGTH)

    @field_validator("action_id")
    @classmethod
    def _validate_action_id(cls, v: str) -> str:
        if not _ACTION_ID_PATTERN.match(v):
            raise ValueError(f"action_id must match ^{_ACTION_ID_PATTERN.pattern[1:-1]}$")
        return v

    @field_validator("capability_id")
    @classmethod
    def _validate_capability_id(cls, v: str) -> str:
        if not _CAPABILITY_ID_PATTERN.match(v):
            raise ValueError(f"capability_id must match ^{_CAPABILITY_ID_PATTERN.pattern[1:-1]}$")
        return v

    @field_validator("action_type")
    @classmethod
    def _validate_action_type(cls, v: str) -> str:
        if not _ACTION_TYPE_PATTERN.match(v):
            raise ValueError(f"action_type must match ^{_ACTION_TYPE_PATTERN.pattern[1:-1]}$")
        return v

    @field_validator("arguments")
    @classmethod
    def _validate_arguments_bounded(cls, v: dict[str, Any]) -> dict[str, Any]:
        if len(v) > _MAX_ACTION_ARGUMENTS:
            raise ValueError(f"arguments must have at most {_MAX_ACTION_ARGUMENTS} entries")
        for key, value in v.items():
            if not isinstance(key, str):
                raise ValueError(f"argument key must be a string, got {type(key).__name__}")
            if len(key) > _MAX_ARGUMENT_KEY_LENGTH:
                raise ValueError(f"argument key exceeds {_MAX_ARGUMENT_KEY_LENGTH} chars")
            if isinstance(value, str) and len(value) > _MAX_ARGUMENT_VALUE_LENGTH:
                raise ValueError(f"argument value for '{key}' exceeds {_MAX_ARGUMENT_VALUE_LENGTH} chars")
            if isinstance(value, (list, dict)):
                raise ValueError(f"argument value for '{key}' must be a scalar, not {type(value).__name__}")
        return v

    @field_validator("dependencies")
    @classmethod
    def _validate_dependencies_format(cls, v: list[str]) -> list[str]:
        for dep in v:
            if not _ACTION_ID_PATTERN.match(dep):
                raise ValueError(f"dependency '{dep}' must match ^{_ACTION_ID_PATTERN.pattern[1:-1]}$")
        return v


class RawManagerDecision(BaseModel):
    """
    Untrusted decision output from the model.

    ONLY these fields may be populated by the model.  Additional fields
    are rejected by ConfigDict(extra="forbid").
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    outcome: str = Field(min_length=1, max_length=32)
    goal: str = Field(min_length=1, max_length=_MAX_GOAL_LENGTH)
    proposed_actions: list[RawActionProposal] = Field(
        default_factory=list, max_length=_MAX_ACTIONS
    )
    required_capabilities: list[str] = Field(default_factory=list, max_length=_MAX_CAPABILITIES)
    risk_level: RiskLevel = RiskLevel.LOW
    approval_required: bool = False
    rationale: str | None = Field(default=None, max_length=_MAX_RATIONALE_LENGTH)
    warnings: list[str] = Field(default_factory=list, max_length=_MAX_WARNINGS)
    uncertainty: float | None = Field(default=None, ge=0.0, le=1.0)

    @field_validator("outcome")
    @classmethod
    def _validate_outcome(cls, v: str) -> str:
        valid = {o.value for o in DecisionOutcome}
        if v not in valid:
            raise ValueError(f"outcome must be one of {sorted(valid)}")
        return v

    @field_validator("required_capabilities")
    @classmethod
    def _validate_required_capabilities(cls, v: list[str]) -> list[str]:
        for cap in v:
            if not _CAPABILITY_ID_PATTERN.match(cap):
                raise ValueError(f"capability '{cap}' must match ^{_CAPABILITY_ID_PATTERN.pattern[1:-1]}$")
        return v

    @field_validator("warnings")
    @classmethod
    def _validate_warnings_bounded(cls, v: list[str]) -> list[str]:
        for warning in v:
            if len(warning) > _MAX_WARNING_LENGTH:
                raise ValueError(f"warning exceeds {_MAX_WARNING_LENGTH} chars")
        return v


# ── Application-controlled input ──────────────────────────────────────────────


class UserIntent(BaseModel):
    """
    Application-controlled user intent.

    The application generates intent_id and normalizes the goal.
    The user_request is treated as untrusted content.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    intent_id: str = Field(min_length=1, max_length=64)
    user_request: str = Field(min_length=1, max_length=_MAX_USER_REQUEST_LENGTH)
    normalized_goal: str = Field(min_length=1, max_length=_MAX_GOAL_LENGTH)
    context: dict[str, Any] = Field(default_factory=dict, max_length=_MAX_CONTEXT_ENTRIES)
    constraints: dict[str, Any] = Field(default_factory=dict, max_length=_MAX_CONSTRAINTS_ENTRIES)
    priority: int = Field(default=0)
    metadata: dict[str, Any] = Field(default_factory=dict, max_length=_MAX_METADATA_ENTRIES)

    @field_validator("intent_id")
    @classmethod
    def _validate_intent_id(cls, v: str) -> str:
        if not re.match(r"^[A-Za-z0-9_-]{1,64}$", v):
            raise ValueError("intent_id must match ^[A-Za-z0-9_-]{1,64}$")
        return v

    @field_validator("normalized_goal")
    @classmethod
    def _validate_normalized_goal(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("normalized_goal must not be empty")
        return v.strip()

    @field_validator("context")
    @classmethod
    def _validate_context_bounded(cls, v: dict[str, Any]) -> dict[str, Any]:
        if len(v) > _MAX_CONTEXT_ENTRIES:
            raise ValueError(f"context must have at most {_MAX_CONTEXT_ENTRIES} entries")
        for key, value in v.items():
            if not isinstance(key, str):
                raise ValueError(f"context key must be a string, got {type(key).__name__}")
            if len(key) > _MAX_CONTEXT_KEY_LENGTH:
                raise ValueError(f"context key exceeds {_MAX_CONTEXT_KEY_LENGTH} chars")
            if isinstance(value, str) and len(value) > _MAX_CONTEXT_VALUE_LENGTH:
                raise ValueError(f"context value for '{key}' exceeds {_MAX_CONTEXT_VALUE_LENGTH} chars")
        return v

    @field_validator("constraints")
    @classmethod
    def _validate_constraints_bounded(cls, v: dict[str, Any]) -> dict[str, Any]:
        if len(v) > _MAX_CONSTRAINTS_ENTRIES:
            raise ValueError(f"constraints must have at most {_MAX_CONSTRAINTS_ENTRIES} entries")
        for key, value in v.items():
            if not isinstance(key, str):
                raise ValueError(f"constraint key must be a string, got {type(key).__name__}")
            if len(key) > _MAX_CONSTRAINTS_KEY_LENGTH:
                raise ValueError(f"constraint key exceeds {_MAX_CONSTRAINTS_KEY_LENGTH} chars")
            if isinstance(value, str) and len(value) > _MAX_CONSTRAINTS_VALUE_LENGTH:
                raise ValueError(f"constraint value for '{key}' exceeds {_MAX_CONSTRAINTS_VALUE_LENGTH} chars")
        return v


# ── Application-controlled output ─────────────────────────────────────────────


class ActionProposal(BaseModel):
    """
    Application-controlled, validated action proposal.

    All fields are controlled by the application after normalization.
    The model proposed a RawActionProposal; the application converted it.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    action_id: str = Field(min_length=1, max_length=64)
    capability_id: CapabilityIdentifier
    action_type: str = Field(min_length=1, max_length=64)
    arguments: dict[str, Any] = Field(default_factory=dict, max_length=_MAX_ACTION_ARGUMENTS)
    dependencies: list[str] = Field(default_factory=list, max_length=_MAX_DEPENDENCIES)
    risk: RiskLevel = RiskLevel.LOW
    approval_required: bool = False
    summary: str = Field(min_length=1, max_length=_MAX_SUMMARY_LENGTH)

    @field_validator("action_id")
    @classmethod
    def _validate_action_id(cls, v: str) -> str:
        if not _ACTION_ID_PATTERN.match(v):
            raise ValueError(f"action_id must match ^{_ACTION_ID_PATTERN.pattern[1:-1]}$")
        return v

    @field_validator("action_type")
    @classmethod
    def _validate_action_type(cls, v: str) -> str:
        if not _ACTION_TYPE_PATTERN.match(v):
            raise ValueError(f"action_type must match ^{_ACTION_TYPE_PATTERN.pattern[1:-1]}$")
        return v


class ManagerDecision(BaseModel):
    """
    Application-controlled, validated manager decision.

    The model produced a RawManagerDecision; the application normalized
    it into this trusted form.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    intent: UserIntent
    outcome: DecisionOutcome
    goal: str = Field(min_length=1, max_length=_MAX_GOAL_LENGTH)
    proposed_actions: list[ActionProposal] = Field(default_factory=list, max_length=_MAX_ACTIONS)
    required_capabilities: list[CapabilityIdentifier] = Field(default_factory=list, max_length=_MAX_CAPABILITIES)
    risk_level: RiskLevel = RiskLevel.LOW
    approval_required: bool = False
    rationale: str | None = Field(default=None, max_length=_MAX_RATIONALE_LENGTH)
    warnings: list[str] = Field(default_factory=list, max_length=_MAX_WARNINGS)
    uncertainty: float | None = Field(default=None, ge=0.0, le=1.0)

    @field_validator("proposed_actions")
    @classmethod
    def _validate_unique_action_ids(cls, v: list[ActionProposal]) -> list[ActionProposal]:
        ids = [a.action_id for a in v]
        if len(ids) != len(set(ids)):
            raise ValueError("duplicate action_id in proposed_actions")
        return v

    @field_validator("warnings")
    @classmethod
    def _validate_warnings_bounded(cls, v: list[str]) -> list[str]:
        for warning in v:
            if len(warning) > _MAX_WARNING_LENGTH:
                raise ValueError(f"warning exceeds {_MAX_WARNING_LENGTH} chars")
        return v


class ManagerResult(BaseModel):
    """
    Final normalized result returned to the application caller.
    """
    model_config = ConfigDict(frozen=True, extra="forbid")

    decision: ManagerDecision | None = None
    outcome: DecisionOutcome
    error: Any = None

    @model_validator(mode="after")
    def _validate_decision_consistency(self) -> "ManagerResult":
        if self.outcome == DecisionOutcome.REJECTED and self.decision is not None:
            raise ValueError("REJECTED outcome must not include a decision")
        if self.outcome != DecisionOutcome.REJECTED and self.decision is None:
            raise ValueError(f"{self.outcome.value} outcome must include a decision")
        if self.error is not None and not isinstance(self.error, _AIManagerError):
            raise ValueError(f"error must be an AIManagerError instance, got {type(self.error).__name__}")
        return self
